#!/usr/bin/env python3
"""mkcharmap.py -- the 8244's character generator, by code: build/charmap.inc.

Codes $20-$5F are ASCII (disp.inc folds lowercase onto them); $00-$1F name
the font's pictures. Anything the font has no glyph for is a blank.
"""
import sys

ROM = "0123456789:$ ?LP+WERTUIOQSDFGHJKAZXCVBM.-*%=YN/#"
SPECIAL = [  # code: glyph
    49,  # $00 ball
    56,  # $01 slope left
    57,  # $02 slope right
    50,  # $03 man right
    51,  # $04 man right, walking
    52,  # $05 man left, walking
    53,  # $06 man left
    58,  # $07 man forward
    47,  # $08 block
    55,  # $09 tree
    54,  # $0A arrow
    48,  # $0B "10"
    60,  # $0C ship 1
    61,  # $0D plane
    62,  # $0E ship 2
    63,  # $0F ship 3
    41,  # $10 times
    42,  # $11 divide
    59,  # $12 backslash
]
SPACE = ROM.index(" ")


def glyph(code):
    if code < 0x20:
        return SPECIAL[code] if code < len(SPECIAL) else SPACE
    c = chr(code)
    return ROM.index(c) if c in ROM else SPACE


def main(out):
    vals = [glyph(c) for c in range(0x60)]
    rows = [", ".join("%3d" % v for v in vals[i:i + 16]) for i in range(0, 0x60, 16)]
    open(out, "w").write(
        "; GENERATED by tools/mkcharmap.py -- do not edit.\n"
        "; code $00-$5F -> 8244 glyph (o2doc appendix C)\n"
        "charmap:\n" + "".join("    db %s\n" % r for r in rows))


if __name__ == "__main__":
    main(sys.argv[1])
